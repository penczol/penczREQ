_POLISH_MARKERS = re.compile(r"[ąćęłńóśźżĄĆĘŁŃÓŚŹŻ]|\b(?:jest|został|została|nie|hasło|konto|użytkownik|request|pozycja|strona|błąd)\b", re.IGNORECASE)


def normalize_language(value: Any, default: Language = DEFAULT_LANGUAGE) -> Language:
    candidate = str(value or "").lower().strip()
    return candidate if candidate in SUPPORTED_LANGUAGES else default  # type: ignore[return-value]


def translate(source: str, language: Any, **values: Any) -> str:
    normalized = normalize_language(language)
    template = EN_BY_PL.get(source, source) if normalized == "en" else source
    return template.format(**values) if values else template


def translator(language: Any) -> Callable[..., str]:
    normalized = normalize_language(language)

    def bound(source: str, **values: Any) -> str:
        return translate(source, normalized, **values)

    return bound


def client_translations(language: Any) -> dict[str, str]:
    return dict(EN_BY_PL) if normalize_language(language) == "en" else {}


def looks_polish(value: str) -> bool:
    return bool(_POLISH_MARKERS.search(value))


def localize_message(message: str, language: Any) -> str:
    """Translate known server messages while retaining deterministic source fallback."""
    normalized = normalize_language(language)
    if normalized == "pl" or not message:
        return message
    exact = EN_BY_PL.get(message)
    if exact:
        return exact

    prefixed = (
        ("Nie można utworzyć administratora Control. ", "Could not create the Control administrator. "),
        ("Hasło odzyskiwania jest nieprawidłowe. ", "The recovery password is invalid. "),
    )
    for source_prefix, target_prefix in prefixed:
        if message.startswith(source_prefix):
            return target_prefix + localize_message(message[len(source_prefix):], normalized)

    # Repository/security validation still carries human-readable source messages.
    # These substitutions cover their bounded dynamic variants without weakening
    # the original validation or authorization checks.
    replacements = (
        (r"^Nieprawidłowy adres lub podsieć proxy: (.+)$", "Invalid proxy address or network: {0}"),
        (r"^Usunięto (\d+) powiadomień\.$", "Deleted notifications: {0}."),
        (r"^TMDB zwróciło błąd HTTP (\d+)\.$", "TMDB returned HTTP error {0}."),
        (r"^Nie można odszyfrować sekretu (.+)\.$", "Could not decrypt secret {0}."),
    )
    for pattern, target in replacements:
        match = re.match(pattern, message)
        if match:
            return target.format(*match.groups())
    return message


def missing_english(sources: set[str]) -> set[str]:
    return {source for source in sources if looks_polish(source) and source not in EN_BY_PL}
